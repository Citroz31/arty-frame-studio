    def _worker_log(self, message: str) -> None:
        if self.loop is not None and not self.closing:
            self.loop.call_soon_threadsafe(self._queue_worker_log, str(message))

    def _queue_worker_log(self, message: str) -> None:
        if self.closing:
            return
        self.worker_messages.append(message)
        if self.log_flush_handle is None and self.loop is not None:
            # Synthesis can emit thousands of lines per second. Batch updates
            # rather than serializing the complete Flet control tree per line.
            self.log_flush_handle = self.loop.call_later(0.1, self._flush_worker_logs)

    def _flush_worker_logs(self) -> None:
        if self.log_flush_handle is not None:
            self.log_flush_handle.cancel()
            self.log_flush_handle = None
        if self.worker_messages:
            messages = "\n".join(self.worker_messages)
            self.worker_messages.clear()
            self._log(messages)

    async def _tool_action(
        self, title: str, action: Callable[[], Any], *, blocks_uart: bool = False
    ) -> Any:
        self.tool_pending = True
        self.programming_pending = blocks_uart
        self.tool_panel.visible = True
        self.tool_progress.visible = True
        self.tool_message.value = f"{title} en cours… Consultez le journal pour les détails."
        self.tool_message.color = AMBER
        self._buttons()
        self._update()
        try:
            result = await asyncio.to_thread(action)
            self._flush_worker_logs()
            self.tool_message.value = f"{title} : opération terminée."
            self.tool_message.color = GREEN
            self._log(self.tool_message.value, GREEN)
            return result
        except Exception as exc:
            self._flush_worker_logs()
            self.tool_message.value = f"{title} : {exc}"
            self.tool_message.color = RED
            self._error(title, exc)
            return None
        finally:
            self.tool_pending = False
            self.programming_pending = False
            self.tool_progress.visible = False
            self._buttons()
            self._update()

