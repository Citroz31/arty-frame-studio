    async def _toggle_connection(self, _: Any = None) -> None:
        if self.serial_pending or self.programming_pending:
            return
        self.serial_pending = True
        self._buttons()
        self._update()
        try:
            async with self.serial_lock:
                if self.device is not None and self.device.connected:
                    if (
                        isinstance(self.device, SerialDevice)
                        and self.device_status is not None
                        and self.device_status.busy
                    ):
                        # Fermer l'UART n'arrête pas la carte : une émission
                        # continue se poursuit jusqu'à STOP, reset ou coupure.
                        self._log(
                            "La carte poursuit son émission après la déconnexion : "
                            "reconnecter puis Arrêter, ou appuyer sur RESET.",
                            AMBER,
                        )
                    await asyncio.to_thread(self.device.close)
                    self.device = None
                    self.device_status = None
                    self.last_sent = None
                    self._firmware_identified(None)
                    self.connection_status.value = "Déconnecté"
                    self.connection_status.color = MUTED
                    self.hardware_status.value = "Aucune émission"
                    self._log("Connexion fermée.")
                else:
                    device: SerialDevice | DemoDevice
                    if self.mode.value == "uart":
                        if not self.port.value:
                            raise ValueError(
                                "Sélectionnez un port série ou branchez la carte puis actualisez."
                            )
                        device = SerialDevice(self.port.value, baudrate=115200)
                        self._log(f"Identification UART sur {self.port.value} · PING puis INFO.")
                    else:
                        device = DemoDevice(core_hz=self.core_hz)
                    try:
                        status = await asyncio.to_thread(device.connect)
                        # INFO donne l'horloge du cœur ; un firmware de révision 1
                        # répond « commande inconnue » et reste à 200 MHz.
                        info = await asyncio.to_thread(device.identify)
                    except Exception:
                        await asyncio.to_thread(device.close)
                        raise
                    self.device = device
                    self.last_sent = None
                    self.command_uncertain = False
                    self._firmware_identified(info)
                    self._status_received(status)
                    label = (
                        "Démo locale · aucun signal physique"
                        if self.mode.value == "demo"
                        else f"Arty · {self.port.value}"
                    )
                    self.connection_status.value = label
                    self.connection_status.color = GREEN
                    self._log(f"Connecté : {label}.", GREEN)
        except Exception as exc:
            self.device = None
            self.device_status = None
            self.last_sent = None
            self._firmware_identified(None)
            if self.mode.value == "uart":
                self.connection_status.color = RED
                if isinstance(exc, CommandTimeout):
                    if exc.opcode == Opcode.INFO:
                        self.connection_status.value = (
                            f"{self.port.value} · PING reçu, identification INFO incomplète"
                        )
                        self.hardware_status.value = "Vérifier la version du firmware et recharger"
                    else:
                        self.connection_status.value = (
                            f"{self.port.value} ouvert · aucune réponse PING compatible"
                        )
                        self.hardware_status.value = "Vérifier bitstream UART, reset et horloge"
                else:
                    self.connection_status.value = f"Connexion impossible · {self.port.value}"
                    self.hardware_status.value = "Consulter le journal"
            self._error("Connexion", exc)
        finally:
            self.serial_pending = False
            self._buttons()
            self._update()

    def _firmware_identified(self, info: FirmwareInfo | None) -> None:
        self.firmware_info = info
        if info is None:
            self.firmware_status.value = "Firmware non identifié"
            self.firmware_status.color = MUTED
            self.hardware_pinout.value = ""
            self._show_leds(None)
            return
        simulated = self.mode.value == "demo"
        build = "référence" if info.build_id == 0 else f"0x{info.build_id:08X}"
        try:
            local = self._firmware_settings()
        except ValueError:
            local = None
        if local is not None and local.build_id == info.build_id and local.core_hz == info.core_hz:
            self.known_firmwares[info.build_id] = local
        known = self.known_firmwares.get(info.build_id)
        if known is not None and known.core_hz != info.core_hz:
            known = None
        if not simulated and known is not None:
            self.hardware_pinout.value = (
                f"Brochage identifié · DATA {known.data_pin} · CLK {known.clock_pin} · "
                f"LATCH {known.latch_pin} · masse commune"
            )
        elif not simulated:
            self.hardware_pinout.value = (
                "Firmware personnalisé · consulter sa configuration pour le brochage ; "
                "INFO transmet un identifiant, pas les noms des broches."
            )
        prefix = "Firmware simulé" if simulated else "Firmware"
        self.firmware_status.value = (
            f"{prefix} révision {info.revision} · cœur {info.core_hz / 1e6:g} MHz · "
            + ("identité locale" if simulated else f"build {build}")
            + firmware_missing(info)
        )
        complete = info.led_test and info.continuous and info.free_clock
        self.firmware_status.color = GREEN if complete else AMBER
        self._log(self.firmware_status.value, self.firmware_status.color)
        if info.core_hz != self.core_hz:
            self._log(
                f"Base de temps passée à {info.core_hz / 1e6:g} MHz, celle du firmware : "
                "fréquence et durées sont requantifiées.",
                AMBER,
            )
            self._apply_core(info.core_hz)

    def _show_leds(self, pattern: int | None) -> None:
        for index, lamp in enumerate(self.led_lamps):
            lamp.bgcolor = LED_ON if pattern is not None and pattern >> index & 1 else LED_OFF
        self._update()

    def _led_step(self, pattern: int | None) -> None:
        # Appelé depuis le thread du test : l'affichage reste sur la boucle Flet.
        if self.loop is not None and not self.closing:
            self.loop.call_soon_threadsafe(self._show_leds, pattern)
        elif self.loop is None:
            self._show_leds(pattern)

    async def _led_test(self, _: Any = None) -> None:
        if (
            self.serial_pending
            or self.programming_pending
            or (self.device_status is not None and self.device_status.busy)
        ):
            return
        self.serial_pending = True
        self._buttons()
        self._update()
        try:
            async with self.serial_lock:
                device = self.device
                if device is None or not device.connected:
                    raise ValueError("Connectez la carte avant le test LED.")
                self._log(
                    "Simulation LED : aperçu des motifs sans carte."
                    if self.mode.value == "demo"
                    else "Test LED : observer LD4 à LD7 (chenillard, toutes allumées, puis état).",
                    BLUE,
                )
                result = await asyncio.to_thread(
                    run_led_test, device, step=self.led_step, on_step=self._led_step
                )
                message = (
                    f"Test LED terminé · {result.commands} commandes simulées · "
                    "aucun signal physique."
                    if self.mode.value == "demo"
                    else f"Test LED terminé · {result.commands} commandes confirmées · "
                    "aller-retour "
                    f"moyen {result.mean_ms:.1f} ms (max {result.max_ms:.1f} ms). Si les LED "
                    "de la carte n'ont pas défilé, le port répond mais pas cette carte."
                )
                self._log(message, GREEN)
        except Exception as exc:
            self._error("Test LED", exc)
        finally:
            self.serial_pending = False
            self._show_leds(None)
            self._buttons()
            self._update()

    def _status_received(self, status: DeviceStatus) -> None:
        self.device_status = status
        if self.last_sent is not None and self.last_sent.continuous:
            # Le compteur 16 bits de la carte reboucle : il témoigne de
            # l'activité, pas du nombre total de trames depuis SEND.
            self.hardware_status.value = (
                f"Émission continue · compteur {status.completed} (modulo 65 536) · "
                "Arrêter pour terminer"
                if status.busy
                else f"Prêt · émission continue arrêtée · compteur {status.completed}"
            )
        else:
            state = "Émission en cours" if status.busy else "Prêt"
            total = f" / {self.last_sent.repeat_count}" if self.last_sent is not None else ""
            self.hardware_status.value = f"{state} · {status.completed}{total} trame(s) terminée(s)"
        if self.command_uncertain:
            self.hardware_status.value += " · Commande non confirmée : STOP ou reconnexion requis"
        self.hardware_status.color = AMBER if status.busy else MUTED
        self._buttons()

    async def _recover_command_timeout(self, exc: CommandTimeout) -> None:
        """Observe the board without repeating a command that may have run."""
        self.command_uncertain = True
        self.last_sent = None
        self.hardware_status.value = "Commande non confirmée · Lecture de STATUS en cours"
        self._log(
            f"{exc.opcode.name} non confirmé : lecture de STATUS, sans répéter la commande.", AMBER
        )
        try:
            if self.device is None:
                raise ValueError("La carte n'est plus connectée.")
            status = await asyncio.to_thread(self.device.status)
            self._status_received(status)
            self._log(
                f"STATUS observé · busy={int(status.busy)} · "
                f"{status.completed} trame(s) terminée(s). "
                "Ce statut ne prouve pas si la commande sans réponse a été exécutée.",
                AMBER,
            )
        except Exception as status_error:
            self.hardware_status.value = "État inconnu · STOP ou reconnexion requis"
            self._log(f"Lecture de STATUS impossible : {status_error}", RED)

    async def _send(self, _: Any) -> None:
        if self.serial_pending or self.programming_pending or self.command_uncertain:
            return
        try:
            config = self._config()
        except (ValueError, TypeError, OverflowError) as exc:
            self._error("Envoi impossible", exc)
            return
        self.serial_pending = True
        self._buttons()
        self._update()
        try:
            async with self.serial_lock:
                if self.device is None or not self.device.connected:
                    raise ValueError("Connectez la carte ou le mode démo avant l'envoi.")
                try:
                    status = await asyncio.to_thread(self.device.send, config)
                except CommandTimeout as exc:
                    await self._recover_command_timeout(exc)
                    raise
                self.last_sent = config
                self._status_received(status)
                repetitions = (
                    "émission continue jusqu'à Arrêter"
                    if config.continuous
                    else f"{config.repeat_count} répétition(s)"
                )
                self._log(
                    f"SEND · {config.bit_count} bits · 0x{config.word:X} · "
                    f"{config.frequency_hz / 1e6:.7g} MHz · {repetitions}.",
                    BLUE,
                )
        except Exception as exc:
            self._error("Envoi de la trame", exc)
        finally:
            self.serial_pending = False
            self._buttons()
            self._update()

    async def _stop(self, _: Any) -> None:
        if self.serial_pending or self.programming_pending:
            return
        self.serial_pending = True
        self._buttons()
        self._update()
        try:
            async with self.serial_lock:
                if self.device is None or not self.device.connected:
                    raise ValueError("Aucun appareil connecté.")
                try:
                    status = await asyncio.to_thread(self.device.stop)
                except CommandTimeout as exc:
                    await self._recover_command_timeout(exc)
                    raise
                self.command_uncertain = False
                self._status_received(status)
                self._log("STOP · sorties ramenées au repos.", AMBER)
        except Exception as exc:
            self._error("Arrêt", exc)
        finally:
            self.serial_pending = False
            self._buttons()
            self._update()

    async def _poll(self) -> None:
        while not self.closing:
            await asyncio.sleep(
                0.2 if self.device_status is not None and self.device_status.busy else 1.0
            )
            if (
                self.serial_pending
                or self.programming_pending
                or self.device is None
                or not self.device.connected
            ):
                continue
            try:
                async with self.serial_lock:
                    if self.device is None or not self.device.connected:
                        continue
                    old_busy = bool(self.device_status is not None and self.device_status.busy)
                    status = await asyncio.to_thread(self.device.status)
                    self._status_received(status)
                    if old_busy and not status.busy:
                        self._log(f"Émission terminée · {status.completed} trame(s).", GREEN)
                    self._update()
            except asyncio.CancelledError:
                raise
            except Exception as exc:
                self._log(f"Connexion interrompue : {exc}", RED)
                async with self.serial_lock:
                    if self.device is not None:
                        await asyncio.to_thread(self.device.close)
                    self.device = None
                    self.device_status = None
                    self.last_sent = None
                    self._firmware_identified(None)
                self.connection_status.value = "Connexion interrompue · reconnectez la carte"
                self.connection_status.color = RED
                self.hardware_status.value = "État de la carte inconnu"
                self._buttons()
                self._update()

