def ticks_from_ns(value: str) -> int:
    """Round a finite nonnegative duration to the hardware's 2.5 ns grid."""
    ns = float(value.strip().replace(",", "."))
    if not math.isfinite(ns) or ns < 0:
        raise ValueError("La durée doit être un nombre positif ou nul.")
    return int(math.floor(ns / 2.5 + 0.5))


def format_duration(ns: float) -> str:
    if ns >= 1e9:
        return f"{ns / 1e9:.4g} s"
    if ns >= 1e6:
        return f"{ns / 1e6:.4g} ms"
    if ns >= 1e3:
        return f"{ns / 1e3:.4g} µs"
    return f"{ns:.4g} ns"


def waveform_signal_points(
    waveform: Waveform, signal: str, width: float
) -> list[tuple[float, float]]:
    """Exact digital steps for one trace, scaled to the available canvas width."""
    if signal not in ("data", "clk", "latch"):
        raise ValueError("Signal inconnu.")
    if not math.isfinite(width) or width < 200:
        raise ValueError("Largeur du chronogramme insuffisante.")
    row = ("data", "clk", "latch").index(signal)
    high, low = 84.0 + row * 64, 114.0 + row * 64
    left, right = 92.0, width - 28

    def position(ticks: int) -> float:
        return left + ticks / waveform.duration_ticks * (right - left)

    first = waveform.transitions[0]
    previous = high if getattr(first, signal) else low
    points = [(position(first.time_ticks), previous)]
    for transition in waveform.transitions[1:]:
        x = position(transition.time_ticks)
        level = high if getattr(transition, signal) else low
        points.append((x, previous))
        if level != previous:
            points.append((x, level))
        previous = level
    if points[-1][0] < right:
        points.append((right, previous))
    return points


def waveform_canvas_shapes(waveform: Waveform, width: float = 1200) -> list[Any]:
    """Render traces and text natively; SVG remains an independent export format."""
    left, right = 92.0, width - 28
    shapes: list[Any] = [
        cv.Rect(0, 0, width, CHART_HEIGHT, border_radius=12, paint=ft.Paint(color="#F8FAFC")),
        cv.Text(
            22,
            14,
            "Chronogramme numérique idéal",
            style=ft.TextStyle(size=16, color="#0F172A", weight=ft.FontWeight.W_700),
        ),
        cv.Text(
            22,
            40,
            f"{waveform.config.bit_count} bits · "
            f"{waveform.config.frequency_hz / 1e6:.6g} MHz · "
            f"{'LSB' if waveform.config.lsb_first else 'MSB'} en premier",
            style=ft.TextStyle(size=12, color="#475569"),
        ),
    ]
    grid_paint = ft.Paint(
        color="#E2E8F0", stroke_width=1, style=ft.PaintingStyle.STROKE, stroke_dash_pattern=[3, 4]
    )
    unit, scale = ("µs", 1000) if waveform.duration_ns >= 1000 else ("ns", 1)
    for index in range(11):
        x = left + index / 10 * (right - left)
        shapes.extend(
            [
                cv.Line(x, 70, x, 260, paint=grid_paint),
                cv.Text(
                    x,
                    270,
                    f"{waveform.duration_ns * index / 10 / scale:.3g}",
                    alignment=ft.alignment.top_center,
                    style=ft.TextStyle(size=10, color="#475569"),
                ),
            ]
        )
    for row, (label, signal, color) in enumerate(SIGNALS):
        points = waveform_signal_points(waveform, signal, width)
        shapes.append(
            cv.Text(
                20,
                91 + row * 64,
                label,
                style=ft.TextStyle(size=13, color=color, weight=ft.FontWeight.W_700),
            )
        )
        elements = [cv.Path.MoveTo(*points[0])]
        elements.extend(cv.Path.LineTo(*point) for point in points[1:])
        shapes.append(
            cv.Path(
                elements=elements,
                paint=ft.Paint(color=color, stroke_width=2, style=ft.PaintingStyle.STROKE),
                data=f"signal:{signal}",
            )
        )
    bit_width = 2 * waveform.config.divider / waveform.duration_ticks * (right - left)
    if bit_width >= 14:
        for index, bit in enumerate(waveform.config.bits):
            sample_tick = (2 * index + 1) * waveform.config.divider
            x = left + sample_tick / waveform.duration_ticks * (right - left)
            shapes.append(
                cv.Text(
                    x,
                    126,
                    str(bit),
                    alignment=ft.alignment.center,
                    style=ft.TextStyle(size=10, color="#2563EB"),
                )
            )
    shapes.append(
        cv.Text(
            22,
            305,
            f"Temps ({unit}) · Échantillonnage DATA au front montant de CLK",
            style=ft.TextStyle(size=11, color="#475569"),
        )
    )
    return shapes


def project_directory() -> Path:
    configured = os.environ.get("ARTY_FRAME_PROJECT")
    if configured:
        return Path(configured).expanduser().resolve()
    if (Path.cwd() / "firmware").is_dir():
        return Path.cwd()
    return Path(__file__).resolve().parents[2]


