    def _toolchain(self) -> Toolchain:
        path = self._path(self.toolchain_path.value)
        return Toolchain(ToolchainConfig.from_json(path), self.project_root)

    def _worker_log(self, message: str) -> None:
        if self.loop is not None and not self.closing:
            self.loop.call_soon_threadsafe(self._queue_worker_log, str(message))

    def _queue_worker_log(self, message: str) -> None:
        if self.closing:
            return
        self.worker_messages.append(message)
        if self.log_flush_handle is None and self.loop is not None:
            # Synthesis can emit thousands of lines per second. Batch updates
            # rather than serializing the complete Flet control tree per line.
            self.log_flush_handle = self.loop.call_later(0.1, self._flush_worker_logs)

    def _flush_worker_logs(self) -> None:
        if self.log_flush_handle is not None:
            self.log_flush_handle.cancel()
            self.log_flush_handle = None
        if self.worker_messages:
            messages = "\n".join(self.worker_messages)
            self.worker_messages.clear()
            self._log(messages)

    async def _tool_action(self, title: str, action: Callable[[], Any]) -> Any:
        self.tool_pending = True
        self.tool_progress.visible = True
        self.tool_message.value = f"{title} en cours… Consultez le journal pour les détails."
        self.tool_message.color = AMBER
        self._buttons()
        self._update()
        try:
            result = await asyncio.to_thread(action)
            self._flush_worker_logs()
            self.tool_message.value = f"{title} : opération terminée."
            self.tool_message.color = GREEN
            self._log(self.tool_message.value, GREEN)
            return result
        except Exception as exc:
            self._flush_worker_logs()
            self.tool_message.value = f"{title} : {exc}"
            self.tool_message.color = RED
            self._error(title, exc)
            return None
        finally:
            self.tool_pending = False
            self.tool_progress.visible = False
            self._buttons()
            self._update()

    async def _doctor(self, _: Any) -> None:
        if self.tool_pending:
            return

        def run() -> Any:
            return self._toolchain().doctor()

        results = await self._tool_action("Vérification des outils", run)
        if results is not None:
            self.doctor_results.controls = []
            for result in results:
                if isinstance(result, dict):
                    name = str(result.get("name", "Outil"))
                    ok = bool(result.get("ok", False))
                    detail = str(result.get("detail", result.get("message", "")))
                else:
                    name = str(getattr(result, "name", "Outil"))
                    ok = bool(getattr(result, "ok", False))
                    detail = str(getattr(result, "detail", getattr(result, "message", result)))
                self.doctor_results.controls.append(
                    ft.Row(
                        [
                            ft.Icon(
                                ft.Icons.CHECK_CIRCLE if ok else ft.Icons.ERROR_OUTLINE,
                                color=GREEN if ok else RED,
                                size=18,
                            ),
                            ft.Text(
                                f"{name} · {detail}",
                                size=12,
                                color=MUTED,
                                selectable=True,
                                expand=True,
                            ),
                        ]
                    )
                )
                self._log(f"{name} · {'OK' if ok else 'INDISPONIBLE'} · {detail}")
            self._update()

    async def _build(self, _: Any) -> None:
        if self.tool_pending:
            return
        result = await self._tool_action(
            "Compilation FPGA",
            lambda: self._toolchain().build(log=self._worker_log),
        )
        if result is not None:
            self.bitstream_path.value = str(result)
            self.tool_message.value = f"Bitstream créé : {result}"
            self._update()

    async def _program(self, _: Any) -> None:
        if self.tool_pending or self.serial_pending:
            return
        try:
            bitstream = self._path(self.bitstream_path.value)
            if not bitstream.is_file():
                raise ValueError(
                    "Bitstream introuvable. Compilez ce projet pour produire "
                    "un bitstream validé, puis utilisez le fichier créé."
                )
        except Exception as exc:
            self._error("Programmation FPGA", exc)
            return
        # Reconfiguration resets the UART receiver. Closing the old session
        # avoids interpreting a stale response as the next command's reply.
        if isinstance(self.device, SerialDevice) and self.device.connected:
            await self._toggle_connection()

        def program() -> bool:
            self._toolchain().program(bitstream, log=self._worker_log)
            return True

        result = await self._tool_action("Programmation SRAM", program)
        if result is not None:
            self._log(
                "Le FPGA est configuré. Connectez le port UART dans Pilotage "
                "pour envoyer des trames.",
                BLUE,
            )

    async def _export_journal(self, _: Any) -> None:
        try:
            path = self._path(self.journal_path.value)
            await asyncio.to_thread(path.parent.mkdir, parents=True, exist_ok=True)
            await asyncio.to_thread(
                path.write_text, "\n".join(self.log_lines) + "\n", encoding="utf-8"
            )
            self._log(f"Journal enregistré : {path}", GREEN)
        except Exception as exc:
            self._error("Export du journal", exc)

    def _clear_journal(self, _: Any) -> None:
        self.log_lines.clear()
        self.journal.controls.clear()
        self._update()

    async def shutdown(self, _: Any = None) -> None:
        self.closing = True
        if self.log_flush_handle is not None:
            self.log_flush_handle.cancel()
            self.log_flush_handle = None
        if self.poll_task is not None:
            self.poll_task.cancel()
            try:
                await self.poll_task
            except asyncio.CancelledError:
                pass
        async with self.serial_lock:
            if self.device is not None:
                await asyncio.to_thread(self.device.close)
            self.device = None

    async def start(self) -> None:
        self.loop = asyncio.get_running_loop()
        self.page.on_disconnect = self.shutdown
        self.page.add(self.layout())
        self._changed()
        self._log("Arty Frame Studio · mode démo disponible sans carte et sans outils FPGA.", BLUE)
        await self._refresh_ports()
        await self._toggle_connection()
        self.poll_task = asyncio.create_task(self._poll())


